# migrate.R - migrate Qlik apps to Qlik Cloud, once.
#
# RUN_MIGRATION.bat runs this file from the project folder. It asks three
# questions (which space, which apps, where to), then for each app in turn:
#   download -> save original.qvs -> unlock Data Manager -> style ->
#   retarget -> save migrated.qvs -> upload -> check -> tag -> notes.txt
# A step that fails stops that app only: it is FAILED, with the reason, and
# the run goes on with the next app. Then one results screen.
#
# Base R only (runs on R 4.3.1). Every contact with Qlik Cloud goes through
# qlik-cli (the path is in qlik_cli_path.txt), via the qlik() function below.

source("shared/json_read.R")              # json_parse(), json_read(), json_get()
source("shared/csv_read.R")               # read_csv_any()
source("2_styling/run_styling.R")         # style_script()
source("3_retargeting/retarget_loads.R")  # retarget_script(), read_qlik_script()

QLIK <- trimws(readLines("qlik_cli_path.txt", warn = FALSE)[1])
FLAGS <- read_csv_any("flags.csv")        # flag, tag, where, pattern, note
OUT_DIR <- "output"
RUN_CSV <- file.path(OUT_DIR, "migrated_apps.csv")
COPY_SUFFIX <- " [mig]"
SCREEN_W <- 72L
DM_MARKER <- "///$autogenerated"
DM_TAB <- "///$tab Unlocked from Data Manager"

# ---- the screen and the keyboard -------------------------------------------

# stdin is opened ONCE and reused: opening it again for every question loses
# whatever was already typed ahead, and readline() does not work under Rscript.
STDIN <- file("stdin")
open(STDIN, "r")

# Print a line, cut to the screen width.
say <- function(...) {
  s <- paste0(...)
  if (nchar(s) > SCREEN_W) s <- paste0(substr(s, 1L, SCREEN_W - 3L), "...")
  cat(s, "\n", sep = "")
}

# Print a line of dashes.
rule <- function() cat(strrep("-", SCREEN_W), "\n", sep = "")

# Ask a question and return the answer typed ("" when there is no more input).
ask <- function(prompt) {
  cat(prompt, "\n", sep = "")
  v <- readLines(STDIN, n = 1L)
  if (length(v)) trimws(v) else ""
}

# Ask for a number from 1 to n; NA when the user types Q or nothing.
ask_number <- function(prompt, n) {
  repeat {
    v <- toupper(ask(prompt))
    if (v %in% c("", "Q")) return(NA_integer_)
    k <- suppressWarnings(as.integer(v))
    if (!is.na(k) && k >= 1L && k <= n) return(k)
    say("Type a number from 1 to ", n, ", or Q to quit.")
  }
}

# Turn "all" or "1,3-5" into row numbers from 1 to n; NULL if it makes no sense.
parse_picks <- function(s, n) {
  s <- tolower(gsub("[[:space:]]", "", s))
  if (s == "all") return(seq_len(n))
  out <- integer(0)
  for (part in strsplit(s, ",", fixed = TRUE)[[1]]) {
    ab <- suppressWarnings(as.integer(strsplit(part, "-", fixed = TRUE)[[1]]))
    if (!length(ab) || length(ab) > 2L || anyNA(ab) || ab[1] > ab[length(ab)]) return(NULL)
    out <- c(out, ab[1]:ab[length(ab)])
  }
  out <- sort(unique(out))
  if (!length(out) || any(out < 1L | out > n)) NULL else out
}

# Print a numbered list.
show_list <- function(items) for (i in seq_along(items)) say(sprintf("[%d] %s", i, items[i]))

# ---- talking to qlik-cli ---------------------------------------------------

# Every qlik command run for the current app, with its reply (for notes.txt).
CALLS <- character(0)

# Every space qlik lists (filled by the first question; used for space names).
SPACES <- NULL

# Run qlik with these arguments and return its output lines. Stops with
# qlik's own words if it exits non-zero, does not answer in time, or prints a
# line starting "Error" (qlik-cli can do that and still exit 0).
qlik <- function(args, timeout = 60) {
  out <- tryCatch(
    suppressWarnings(system2(QLIK, shQuote(args), stdout = TRUE, stderr = TRUE,
                             timeout = timeout)),
    error = function(e) structure(conditionMessage(e), status = -1L))
  status <- attr(out, "status")
  if (is.null(status)) status <- 0L
  out <- as.character(out)
  # Record the command (arguments with spaces in quotes) and its reply.
  shown <- ifelse(grepl(" ", args), paste0("\"", args, "\""), args)
  CALLS <<- c(CALLS, paste("$ qlik", paste(shown, collapse = " ")),
              paste("  exit", status), paste0("  ", out), "")
  said <- paste(trimws(out[nzchar(trimws(out))]), collapse = " ")
  if (status == 124L) stop("qlik did not answer within ", timeout, " seconds", call. = FALSE)
  if (status != 0L) stop("qlik exit ", status, ": ", said, call. = FALSE)
  if (any(grepl("^[[:space:]]*(error|fatal)\\b", out, ignore.case = TRUE)))
    stop("qlik said: ", said, call. = FALSE)
  out
}

# Run a qlik command that answers in JSON and return the reply, parsed.
qlik_json <- function(args, timeout = 60) {
  txt <- paste(qlik(c(args, "--json"), timeout), collapse = "\n")
  tryCatch(json_parse(txt), error = function(e)
    stop("qlik's reply was not JSON: ", substr(txt, 1L, 200L), call. = FALSE))
}

# The rows of a listing reply: a bare list, or the list under "data".
rows_of <- function(reply) {
  if (is.null(names(reply))) return(reply)
  if (!"data" %in% names(reply))
    stop("unexpected reply from qlik: no 'data' in it (keys: ",
         paste(names(reply), collapse = ", "), ")", call. = FALSE)
  reply$data
}

# Run a qlik listing command, following its pages, and return every row.
# --limit is always sent: without it qlik quietly returns only its first page.
qlik_list <- function(args) {
  args <- c(args, "--limit", "100")
  rows <- list()
  token <- NULL
  seen <- character(0)
  for (page in 1:100) {
    reply <- qlik_json(if (is.null(token)) args else c(args, "--next", token))
    rows <- c(rows, rows_of(reply))
    nxt <- json_get(reply, "links", "next")
    href <- if (is.character(nxt)) nxt else json_get(nxt, "href")
    m <- if (is.character(href)) regmatches(href, regexpr("[?&]next=[^&]+", href)) else character(0)
    if (!length(m)) break
    token <- sub("^[?&]next=", "", m)
    if (token %in% seen) break
    seen <- c(seen, token)
  }
  rows
}

# One text field from each row of a listing ("" where it is missing).
field <- function(rows, key) {
  vapply(rows, function(r) {
    v <- r[[key]]
    if (is.null(v) || !length(v)) "" else as.character(v[[1]])
  }, character(1))
}

# All spaces, sorted by name: data.frame(id, name, type).
list_spaces <- function() {
  rows <- qlik_list(c("space", "ls"))
  df <- data.frame(id = field(rows, "id"), name = field(rows, "name"),
                   type = field(rows, "type"), stringsAsFactors = FALSE)
  if (any(!nzchar(df$id))) stop("qlik's space list has rows with no id", call. = FALSE)
  df[order(df$name, df$id), , drop = FALSE]
}

# The apps in one space, sorted by name: data.frame(id, name).
list_apps <- function(space_id) {
  rows <- qlik_list(c("app", "ls", "--spaceId", space_id))
  df <- data.frame(id = field(rows, "id"), name = field(rows, "name"),
                   stringsAsFactors = FALSE)
  if (any(!nzchar(df$id))) stop("qlik's app list has rows with no id", call. = FALSE)
  df[order(df$name, df$id), , drop = FALSE]
}

# An app's item record (the hub's entry for it: item id, space), or NULL.
item_of <- function(app_id) {
  rows <- qlik_list(c("item", "ls", "--resourceIds", app_id, "--resourceType", "app"))
  hit <- rows[field(rows, "resourceId") == app_id]
  if (length(hit)) hit[[1]] else NULL
}

# A space as a person reads it: its name in quotes, or what kind of place it is.
space_label <- function(id) {
  if (is.na(id)) return("a space this tool cannot see")
  if (!nzchar(id)) return("a personal space")
  k <- match(id, SPACES$id)
  if (is.na(k)) id else paste0("\"", SPACES$name[k], "\"")
}

# ---- 1. the questions ----------------------------------------------------------

# Ask which space, which apps and where to. Returns the plan, or NULL to stop.
ask_plan <- function() {
  say("1. Which space are the apps in?")
  SPACES <<- list_spaces()
  show_list(sprintf("%s  (%s)", SPACES$name, SPACES$type))
  k <- ask_number("Space number (Q to quit):", nrow(SPACES))
  if (is.na(k)) return(NULL)
  from <- SPACES[k, ]

  say("")
  say("2. Which apps in \"", from$name, "\"?")
  apps <- list_apps(from$id)
  if (!nrow(apps)) { say("That space has no apps."); return(NULL) }
  show_list(twin_labels(apps))
  repeat {
    v <- ask("Apps: all, or numbers like 1,3-5 (Q to quit):")
    if (toupper(v) %in% c("", "Q")) return(NULL)
    picks <- parse_picks(v, nrow(apps))
    if (!is.null(picks)) break
    say("Type all, or numbers from the list like 1,3-5, or Q to quit.")
  }
  apps <- apps[picks, , drop = FALSE]
  apps$label <- twin_labels(apps)

  say("")
  say("3. Where should the finished apps go?")
  say("[1] Back into \"", from$name, "\" - overwrite the originals")
  say("[2] Into another space - as copies named \"<app>", COPY_SUFFIX, "\"")
  where <- ask_number("Choice (Q to quit):", 2L)
  if (is.na(where)) return(NULL)
  to <- from
  if (where == 2L) {
    say("Which space should the copies go to?")
    show_list(sprintf("%s  (%s)", SPACES$name, SPACES$type))
    j <- ask_number("Space number (Q to quit):", nrow(SPACES))
    if (is.na(j)) return(NULL)
    to <- SPACES[j, ]
  }

  say("")
  rule()
  say(nrow(apps), " app(s) from \"", from$name, "\"")
  say(if (where == 2L) paste0("  -> copies in \"", to$name, "\"")
      else "  -> overwrite the originals in place")
  say("Download, style + retarget, upload, then check each one.")
  rule()
  if (ask("Type YES to start, anything else to stop:") != "YES") return(NULL)
  list(apps = apps, from = from, to = to, copy = where == 2L)
}

# ---- 2. one app ------------------------------------------------------------------

# Each app's name, with the first 6 characters of its id added when another
# app in the list has the same name (so the two can be told apart).
twin_labels <- function(apps) {
  n <- tolower(apps$name)
  twin <- duplicated(n) | duplicated(n, fromLast = TRUE)
  paste0(apps$name, ifelse(twin, paste0(" ", substr(apps$id, 1L, 6L)), ""))
}

# A name made safe to use as a Windows folder name.
folder_name <- function(name) {
  f <- gsub('[<>:"/\\\\|?*[:cntrl:]]+', "_", name)
  f <- sub("[. ]+$", "", trimws(gsub("[[:space:]]+", " ", f)))
  ifelse(nzchar(f), f, "unnamed")
}

# Run one step; if it fails, stop with the step's name in front of the reason.
step <- function(what, expr) {
  tryCatch(expr, error = function(e)
    stop(what, " failed - ", conditionMessage(e), call. = FALSE))
}

# 2a. Download an app's definition (no data) into a new folder; returns the
# path of its script.qvs.
download_app <- function(app_id, into) {
  qlik(c("app", "unbuild", "--app", app_id, "--dir", into, "--no-data"), timeout = 600)
  script <- file.path(into, "script.qvs")
  if (!file.exists(script)) stop("qlik wrote no script.qvs", call. = FALSE)
  script
}

# 2c. Unlock a Data Manager section: delete every `///$autogenerated` line and
# rename the `///$tab` line above it. While that marker is there, Qlik rebuilds
# the section itself and throws an uploaded script away. Every other byte is
# kept exactly. `text` is the whole script as one string; returns
# list(text, n) where n is how many markers were removed.
unlock_data_manager <- function(text) {
  none <- list(text = text, n = 0L)
  if (!grepl(DM_MARKER, text, fixed = TRUE, useBytes = TRUE)) return(none)
  x <- text
  Encoding(x) <- "bytes"
  lines <- regmatches(x, gregexpr("[^\n]*\n|[^\n]+$", x, useBytes = TRUE))[[1]]
  eol <- rep("", length(lines))
  k <- regexpr("\r?\n$", lines, useBytes = TRUE)
  eol[k > 0L] <- regmatches(lines, k)
  body <- substr(lines, 1L, nchar(lines, type = "bytes") - nchar(eol, type = "bytes"))
  bom <- rep("", length(lines))
  if (length(lines) && grepl("^\xef\xbb\xbf", lines[1], useBytes = TRUE)) {
    bom[1] <- substr(lines[1], 1L, 3L)
    body[1] <- substr(body[1], 4L, nchar(body[1], type = "bytes"))
  }
  bare <- gsub("^[ \t]+|[ \t]+$", "", body, useBytes = TRUE)
  hit <- which(bare == DM_MARKER)
  if (!length(hit)) return(none)
  tabs <- which(grepl("^///\\$tab ", bare, useBytes = TRUE))
  for (h in hit) {
    t <- tabs[tabs < h]
    if (length(t)) lines[max(t)] <- paste0(bom[max(t)], DM_TAB, eol[max(t)])
  }
  if (1L %in% hit && nzchar(bom[1]) && length(lines) > 1L)
    lines[2L] <- paste0(bom[1], lines[2L])
  list(text = paste(lines[-hit], collapse = ""), n = length(hit))
}

# 2g. Copy an app into a space, make sure it landed there (one move attempt if
# not), and return the copy's id. A copy can land in the wrong space with no
# error at all, which is why its place is checked.
copy_app <- function(app, space) {
  reply <- qlik_json(c("app", "copy", app$id, "--attributes-spaceId", space$id,
                       "--attributes-name", paste0(app$name, COPY_SUFFIX)))
  id <- json_get(reply, "attributes", "id")
  if (is.null(id)) id <- json_get(reply, "id")
  if (!is.character(id) || !nzchar(id)) stop("qlik's copy reply has no app id", call. = FALSE)
  if (id %in% list_apps(space$id)$id) return(id)
  item <- tryCatch(item_of(id), error = function(e) NULL)
  landed <- if (is.null(item)) NA else field(list(item), "spaceId")
  why <- tryCatch({
    qlik_json(c("app", "space", "update", id, "--spaceId", space$id))
    if (id %in% list_apps(space$id)$id) "" else "it is still not there"
  }, error = function(e) conditionMessage(e))
  if (nzchar(why))
    stop("it landed in ", space_label(landed), ", not in \"", space$name,
         "\", and moving it there failed (copy id ", id, "): ", why, call. = FALSE)
  id
}

# 2g. Write a script into an app. Script only, never a reload.
build_app <- function(app_id, script) {
  qlik(c("app", "build", "--app", app_id, "--script", script, "--no-reload", "--silent"))
}

# A script's lines for comparing: line endings and trailing blank lines ignored.
script_lines <- function(path) {
  x <- sub("\r$", "", readLines(path, warn = FALSE))
  while (length(x) && !nzchar(x[length(x)])) x <- x[-length(x)]
  x
}

# 2h. Download the app again and compare its script with ours.
check_upload <- function(app_id, script, into) {
  a <- script_lines(download_app(app_id, into))
  b <- script_lines(script)
  if (identical(a, b)) return(invisible(TRUE))
  n <- min(length(a), length(b))
  k <- which(a[seq_len(n)] != b[seq_len(n)])
  stop(sprintf("the script in the cloud is not migrated.qvs (cloud %d lines, ours %d, first difference at line %d)",
               length(a), length(b), if (length(k)) k[1] else n + 1L), call. = FALSE)
}

# 2i. Which flags.csv flags an app shows (TRUE/FALSE per flag), read from its
# script (live code and comments apart) and from its sheets, dimensions,
# measures and variables in the downloaded folder.
find_flags <- function(script, bundle) {
  tok <- read_qlik_script(script)
  com <- tok$type == "COMMENT"
  by_line <- function(keep, sep)
    unname(vapply(split(tok$text[keep], tok$line[keep]), paste, character(1), collapse = sep))
  files <- c(list.files(file.path(bundle, "objects"), "[.]json$", full.names = TRUE),
             file.path(bundle, c("dimensions.json", "measures.json", "variables.json")))
  files <- files[file.exists(files)]
  pools <- list(script = by_line(!com, ""), comments = by_line(com, " "),
                objects = unlist(lapply(files, function(f)
                  tryCatch(unlist(json_read(f)), error = function(e) NULL)), use.names = FALSE))
  hits <- vapply(seq_len(nrow(FLAGS)), function(i) {
    pool <- unlist(pools[trimws(strsplit(FLAGS$where[i], ",", fixed = TRUE)[[1]])], use.names = FALSE)
    any(grepl(FLAGS$pattern[i], pool, ignore.case = TRUE, perl = TRUE))
  }, logical(1))
  setNames(hits, FLAGS$flag)
}

# The id of the collection (hub tag) with this name, made if it does not exist yet.
collection_id <- function(name) {
  rows <- qlik_list(c("collection", "ls"))
  k <- match(name, field(rows, "name"))
  if (!is.na(k)) return(field(rows, "id")[k])
  reply <- qlik_json(c("collection", "create", "--name", name, "--type", "public"))
  id <- json_get(reply, "id")
  if (is.null(id)) id <- json_get(reply, "attributes", "id")
  if (!is.character(id) || !nzchar(id)) stop("qlik's reply has no collection id", call. = FALSE)
  id
}

# 2i. Tag an app in the hub with each of these tags it does not have yet.
tag_app <- function(app_id, tags) {
  if (!length(tags)) return(invisible())
  item <- item_of(app_id)
  if (is.null(item)) stop("qlik has no hub item for app ", app_id, call. = FALSE)
  have <- field(rows_of(qlik_json(c("item", "collections", item$id))), "name")
  for (tag in setdiff(tags, have))
    qlik(c("collection", "item", "create", "--collectionId", collection_id(tag), "--id", item$id))
}

# Migrate one app into output/<its label>/. Returns what happened, for the
# results screen and migrated_apps.csv.
migrate_app <- function(app, plan) {
  CALLS <<- character(0)
  dir <- file.path(OUT_DIR, folder_name(app$label))
  unlink(dir, recursive = TRUE)          # nothing from an earlier run is ever reused
  dir.create(dir, recursive = TRUE)
  scratch <- file.path(dir, "scratch")
  dir.create(scratch)
  on.exit(unlink(scratch, recursive = TRUE))
  original <- file.path(dir, "original.qvs")
  migrated <- file.path(dir, "migrated.qvs")
  target <- ""; unlocked <- NA; rt <- NULL; flags <- NULL; checked <- FALSE

  failed <- tryCatch({
    # a. download it
    script <- step("Download", download_app(app$id, file.path(scratch, "download")))
    # b. keep the script exactly as downloaded; read its flags while the rest
    #    of the download is here (they are tagged in step i)
    file.copy(script, original)
    flags <- step("Flag check", find_flags(original, file.path(scratch, "download")))
    # c. unlock a Data Manager section
    dm <- unlock_data_manager(readChar(original, file.info(original)$size, useBytes = TRUE))
    unlocked <- dm$n
    writeBin(charToRaw(dm$text), file.path(scratch, "unlocked.qvs"))
    # d. style it
    step("Styling", style_script(file.path(scratch, "unlocked.qvs"), file.path(scratch, "styled.qvs")))
    # e + f. retarget it, writing migrated.qvs
    rt <- step("Retargeting", retarget_script(file.path(scratch, "styled.qvs"), migrated))
    # g. upload: into the original, or into a checked copy in the other space
    target <- if (plan$copy) step("Copy", copy_app(app, plan$to)) else app$id
    step("Upload", build_app(target, migrated))
    # h. check: what is in the cloud now must be exactly migrated.qvs
    step("Check", check_upload(target, migrated, file.path(scratch, "check")))
    checked <- TRUE
    # i. tag the uploaded app with each flag found
    step("Tagging", tag_app(target, FLAGS$tag[flags]))
    ""
  }, error = function(e) conditionMessage(e))

  res <- list(app = app$label, result = if (nzchar(failed)) "FAILED" else "ok",
              reason = failed, folder = dir,
              retargeted = if (is.null(rt)) "" else paste(rt$done, "of", rt$total),
              flags = if (is.null(flags)) setNames(rep("", nrow(FLAGS)), FLAGS$flag)
                      else ifelse(flags, "yes", "no"))
  write_notes(app, plan, res, target, checked, unlocked, rt)
  res
}

# 2j. Write output/<app>/notes.txt: what happened, what is left to do by hand,
# and every qlik command run with its reply.
write_notes <- function(app, plan, res, target, checked, unlocked, rt) {
  went <- if (!nzchar(target)) "not uploaded (see Result)"
          else if (plan$copy) paste0("a copy named \"", app$name, COPY_SUFFIX, "\" (id ", target,
                                     ") in \"", plan$to$name, "\"")
          else paste0("over the original (id ", target, ") in \"", plan$from$name, "\"")
  flag_text <- paste(names(res$flags), ifelse(nzchar(res$flags), res$flags, "not checked"),
                     collapse = ", ")
  lines <- c(
    paste("App:", app$name, paste0("(id ", app$id, ")")),
    paste("Run:", format(Sys.time(), "%Y-%m-%d %H:%M")),
    paste0("From: \"", plan$from$name, "\""),
    paste("Went to:", went),
    paste0("Result: ", res$result, if (nzchar(res$reason)) paste(" -", res$reason)),
    paste("Checked:", if (checked) "yes - the script in the cloud is exactly migrated.qvs"
                      else "no"),
    paste("Data Manager:", if (is.na(unlocked)) "not checked" else if (unlocked > 0L)
      paste0("unlocked (removed ", unlocked, " ", DM_MARKER, " line(s), tab renamed to \"",
             sub("^///\\$tab ", "", DM_TAB), "\")") else "no locked section"),
    paste("Flags:", flag_text),
    "",
    if (is.null(rt)) "Not retargeted (the run stopped before that step)." else rt$lines,
    "",
    "Qlik commands run, each with its reply:",
    if (length(CALLS)) CALLS else "  (none)")
  writeLines(lines, file.path(res$folder, "notes.txt"))
}

# ---- 3. the record of every run ------------------------------------------------

# Add one row per app to output/migrated_apps.csv (the header the first time).
append_run_csv <- function(res, plan) {
  row <- data.frame(date = format(Sys.time(), "%Y-%m-%d %H:%M"), app = res$app,
                    from_space = plan$from$name, to_space = plan$to$name,
                    result = res$result, retargeted = res$retargeted,
                    t(res$flags), stringsAsFactors = FALSE, check.names = FALSE)
  new <- !file.exists(RUN_CSV)
  utils::write.table(row, RUN_CSV, sep = ",", row.names = FALSE, col.names = new,
                     append = !new, qmethod = "double")
}

# ---- 4. the run ----------------------------------------------------------------

# Ask, migrate each app in turn, then show the results screen.
main <- function() {
  say("Qlik app migration")
  rule()
  if (!file.exists(QLIK)) {
    say("qlik-cli not found at: ", QLIK)
    say("Put the right path in qlik_cli_path.txt")
    return(invisible())
  }
  plan <- tryCatch(ask_plan(), error = function(e) {
    say("Could not talk to Qlik Cloud: ", conditionMessage(e))
    say("Is qlik-cli signed in? (qlik context use <name>)")
    NULL
  })
  if (is.null(plan)) { say("Stopped. Nothing in the cloud was changed."); return(invisible()) }

  dir.create(OUT_DIR, showWarnings = FALSE)
  n <- nrow(plan$apps)
  results <- vector("list", n)
  say("")
  for (i in seq_len(n)) {
    say(sprintf("[%d/%d] %s ...", i, n, plan$apps$label[i]))
    results[[i]] <- migrate_app(plan$apps[i, ], plan)
    say("      ", results[[i]]$result)
    append_run_csv(results[[i]], plan)
  }

  ok <- vapply(results, function(r) r$result == "ok", logical(1))
  say("")
  rule()
  say("Results: ", sum(ok), " ok, ", sum(!ok), " FAILED")
  for (r in results) {
    say(sprintf("  %-6s %s", r$result, r$app))
    if (nzchar(r$reason)) say("         ", r$reason)
  }
  rule()
  say("Each app's files: ", OUT_DIR, "\\<app name>\\")
